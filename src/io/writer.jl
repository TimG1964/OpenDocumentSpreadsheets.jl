# Writing the ODF package. See D-005 (mimetype entry), D-006 (ODF version) and F-016 (IO
# requirements of zip_append_archive).

const WRITABLE_ODF_VERSIONS = ("1.3", "1.4")
const DEFAULT_ODF_VERSION = "1.4"     # D-006

_check_version(v::AbstractString) = v in WRITABLE_ODF_VERSIONS ||
    throw(ArgumentError("cannot write ODF version $(repr(v)); choose one of $(join(WRITABLE_ODF_VERSIONS, ", "))"))

"""
    _ChunkedIO(dest; limit = 1 MiB)

An `IO` that gathers small writes in a buffer and hands them to `dest` a chunk at a time,
so that a large part is written into the zip (or a file) as it is made, never held whole.
A write of a chunk or more goes straight through. `_flush!` hands over what is
left. The buffer's memory is reused from chunk to chunk.
"""
mutable struct _ChunkedIO <: IO
    buf::IOBuffer
    dest::IO
    limit::Int
end
_ChunkedIO(dest::IO; limit::Int = 1 << 20) = _ChunkedIO(IOBuffer(), dest, limit)

function _flush!(c::_ChunkedIO)
    position(c.buf) == 0 && return nothing
    v = take!(c.buf)
    write(c.dest, v)
    c.buf = IOBuffer(v; read = false, write = true, truncate = true)
    return nothing
end

function Base.unsafe_write(c::_ChunkedIO, p::Ptr{UInt8}, n::UInt)
    if n >= c.limit
        _flush!(c)
        return unsafe_write(c.dest, p, n)
    end
    r = unsafe_write(c.buf, p, n)
    position(c.buf) >= c.limit && _flush!(c)
    return r
end
function Base.write(c::_ChunkedIO, b::UInt8)
    write(c.buf, b)
    position(c.buf) >= c.limit && _flush!(c)
    return 1
end
# Strings and characters go to the buffer's own `write` methods: through the generic
# `unsafe_write` path, a short string took twice as long (the writers make many).
@inline function Base.write(c::_ChunkedIO, s::Union{String,SubString{String}})
    ncodeunits(s) >= c.limit && return Int(unsafe_write(c, pointer(s), UInt(ncodeunits(s))))
    n = write(c.buf, s)
    position(c.buf) >= c.limit && _flush!(c)
    return n
end
@inline function Base.write(c::_ChunkedIO, ch::Char)
    n = write(c.buf, ch)
    position(c.buf) >= c.limit && _flush!(c)
    return n
end
Base.isopen(c::_ChunkedIO) = isopen(c.dest)
Base.iswritable(::_ChunkedIO) = true
Base.isreadable(::_ChunkedIO) = false

# Runs `f(io)` with `io` a `_ChunkedIO` over `dest`, and hands over the rest at the end.
function _write_chunked(f, dest::IO)
    c = _ChunkedIO(dest)
    f(c)
    _flush!(c)
    return nothing
end

"""
    PackagePart(name, data; mediatype = guessed from the extension, compress = true)

One part to write into a zipped package. `data` is a `String` (XML), bytes, or a function
`data(io)` that writes the part to `io` as it makes it. `mimetype` and
`META-INF/manifest.xml` are generated by [`write_package`](@ref) and must not be passed as
parts.
"""
struct PackagePart
    name::String
    data::Union{String,Vector{UInt8},Function,Nothing}   # nothing: listed in the manifest only
    mediatype::String
    compress::Bool
    # asked when the part's turn comes (after the parts before it are written): whether it is
    # written and listed; nothing: always (an embedded object whose frame may be gone, phase 8)
    keep::Union{Nothing,Function}
end
PackagePart(name::String, data, mediatype::String, compress::Bool) = PackagePart(name, data, mediatype, compress, nothing)

# A directory that the manifest lists with a media type but the zip holds no entry for, such as an
# embedded chart's `Object 1/` (LibreOffice writes it so, and needs it to load the chart).
manifest_entry(name::AbstractString, mediatype::AbstractString; keep::Union{Nothing,Function} = nothing) =
    PackagePart(String(name), nothing, String(mediatype), false, keep)

function PackagePart(name::AbstractString, data::Union{AbstractString,AbstractVector{UInt8},Function};
                     mediatype::AbstractString = guess_mediatype(name),
                     compress::Bool = !_already_compressed(name), keep::Union{Nothing,Function} = nothing)
    PackagePart(String(name), data isa Function ? data : data isa AbstractString ? String(data) : Vector{UInt8}(data),
                String(mediatype), compress, keep)
end

_kept(p::PackagePart) = p.keep === nothing || p.keep()::Bool

const _MEDIATYPES = Dict(
    ".xml" => "text/xml",
    ".rdf" => "application/rdf+xml",
    ".png" => "image/png",
    ".jpg" => "image/jpeg", ".jpeg" => "image/jpeg",
    ".gif" => "image/gif",
    ".svg" => "image/svg+xml",
    ".bmp" => "image/bmp",
    ".tif" => "image/tiff", ".tiff" => "image/tiff",
    ".webp" => "image/webp",
)

"""
    guess_mediatype(name) -> String

The media type for a part name, from its extension. Unknown extensions give
`application/octet-stream`.
"""
guess_mediatype(name::AbstractString) =
    get(_MEDIATYPES, lowercase(splitext(name)[2]), "application/octet-stream")

# Deflating already-compressed formats only costs time.
_already_compressed(name::AbstractString) =
    lowercase(splitext(name)[2]) in (".png", ".jpg", ".jpeg", ".gif", ".webp")

const _RESERVED_PARTS = ("mimetype", "META-INF/manifest.xml")

function _check_parts(parts)
    seen = Set{String}()
    for p in parts
        p.name in _RESERVED_PARTS &&
            throw(ArgumentError("$(repr(p.name)) is generated by write_package and must not be passed as a part"))
        (isempty(p.name) || startswith(p.name, "/")) &&
            throw(ArgumentError("invalid part name $(repr(p.name))"))
        p.name in seen && throw(ArgumentError("duplicate part name $(repr(p.name))"))
        push!(seen, p.name)
    end
    "content.xml" in seen || throw(ArgumentError("a package must have a content.xml part"))
end

"""
    manifest_xml(parts, mediatype, version) -> String

The text of `META-INF/manifest.xml` for the given parts.
"""
function manifest_xml(parts, mediatype::AbstractString, version::AbstractString)
    io = IOBuffer()
    print(io, """<?xml version="1.0" encoding="UTF-8"?>\n""",
          """<manifest:manifest xmlns:manifest="$NS_MANIFEST" manifest:version="$(_xattr(version))">\n""",
          """ <manifest:file-entry manifest:full-path="/" manifest:version="$(_xattr(version))" manifest:media-type="$mediatype"/>\n""")
    for p in parts
        # a directory entry is listed only when it has a media type (LibreOffice lists its
        # Configurations2/ folder so)
        endswith(p.name, "/") && isempty(p.mediatype) && continue
        print(io, """ <manifest:file-entry manifest:full-path="$(_xattr(p.name))" manifest:media-type="$(_xattr(p.mediatype))"/>\n""")
    end
    print(io, "</manifest:manifest>\n")
    String(take!(io))
end

_le16(io, x) = write(io, htol(UInt16(x)))
_le32(io, x) = write(io, htol(UInt32(x)))

# A complete zip archive containing only the "mimetype" entry: first, stored (method 0),
# no extra field, so the media type starts at byte 38 as ODF Part 2 §3.3 requires.
# ZipArchives always adds an extra field (F-001), so this one entry is written by hand and
# the remaining parts are appended with `zip_append_archive` (D-005). Must start at
# position 0 of the target.
function _write_mimetype_zip(io::IO, mediatype::AbstractString)
    data = codeunits(mediatype)
    crc = ZipArchives.zip_crc32(data)
    n = length(data)
    dostime, dosdate = 0x0000, 0x0021          # 1980-01-01 00:00, as fixed as possible
    # local file header
    _le32(io, 0x04034b50); _le16(io, 10); _le16(io, 0); _le16(io, 0)   # signature, version needed, flags, stored
    _le16(io, dostime); _le16(io, dosdate)
    _le32(io, crc); _le32(io, n); _le32(io, n)
    _le16(io, 8); _le16(io, 0)                                         # name length, extra length
    write(io, "mimetype"); write(io, data)
    # central directory entry
    _le32(io, 0x02014b50); _le16(io, 20); _le16(io, 10); _le16(io, 0); _le16(io, 0)
    _le16(io, dostime); _le16(io, dosdate)
    _le32(io, crc); _le32(io, n); _le32(io, n)
    _le16(io, 8); _le16(io, 0); _le16(io, 0); _le16(io, 0); _le16(io, 0)
    _le32(io, 0); _le32(io, 0)                                         # attributes, local header offset
    write(io, "mimetype")
    # end of central directory
    _le32(io, 0x06054b50); _le16(io, 0); _le16(io, 0); _le16(io, 1); _le16(io, 1)
    _le32(io, 46 + 8); _le32(io, 30 + 8 + n); _le16(io, 0)
    nothing
end

# `manifest`: its text, or a function of the parts written that makes it (when some parts may not
# be: `keep`).
function _append_parts!(w::ZipArchives.ZipWriter, parts, manifest::Union{String,Function})
    written = PackagePart[]
    for p in parts
        _kept(p) || continue
        push!(written, p)
        p.data === nothing && continue       # in the manifest only
        if endswith(p.name, "/")             # a directory entry, such as Configurations2/
            ZipArchives.zip_mkdir(w, p.name)
            continue
        end
        ZipArchives.zip_newfile(w, p.name; compress = p.compress)
        p.data isa Function ? _write_chunked(p.data, w) : write(w, p.data)
        ZipArchives.zip_commitfile(w)
    end
    ZipArchives.zip_newfile(w, "META-INF/manifest.xml"; compress = true)
    write(w, manifest isa Function ? manifest(written) : manifest)
    ZipArchives.zip_commitfile(w)
end

"""
    write_package(dest, parts; mediatype = MEDIATYPE_ODS, version = "1.4")

Write a zipped ODF package to `dest`, which is a file path or an `IO`.
- `mimetype` is written first, stored and with no extra field.
- `parts` (a collection of [`PackagePart`](@ref)s) follow in the given order.
- `META-INF/manifest.xml` is written last, listing every part, with `manifest:version`
  set to `version` (`"1.4"` by default, `"1.3"` on request).
- `check_version = false` allows any `version`: a patched file's manifest gives its
  `content.xml`'s version, whatever it is, since LibreOffice refuses a package whose two
  versions differ (F-067, D-094).

When writing to an `IO`, the package is built in memory and then copied, because the zip
writer needs a readable, seekable target that starts empty. The memory cost is
about the compressed size. The `IO` is left open.
"""
function write_package(path::AbstractString, parts; mediatype::AbstractString = MEDIATYPE_ODS,
                       version::AbstractString = DEFAULT_ODF_VERSION, check_version::Bool = true)
    check_version && _check_version(version)
    _check_parts(parts)
    mediatype in SPREADSHEET_MEDIATYPES || throw(ArgumentError("unsupported media type $(repr(mediatype))"))
    manifest = written -> manifest_xml(written, mediatype, version)
    _write_replacing(path) do tmp
        open(io -> _write_mimetype_zip(io, mediatype), tmp, "w")
        ZipArchives.zip_append_archive(w -> _append_parts!(w, parts, manifest), tmp)
    end
    path
end

# Writes the file at `path` as `write(tmp)` writes a temporary file beside it, which then replaces
# `path`: parts are made as they are written, so a failure part-way would otherwise leave `path`
# truncated, and saving back to the file that was read would lose it (code review, Phase 1 item 3).
# A link is followed, so the file it points to is replaced, not the link.
function _write_replacing(write::Function, path::AbstractString)
    target = islink(path) ? realpath(path) : path
    tmp = tempname(dirname(abspath(target)); cleanup = false)
    try
        write(tmp)
        mv(tmp, target; force = true)
    catch
        rm(tmp; force = true)
        rethrow()
    end
    return path
end

function write_package(io::IO, parts; mediatype::AbstractString = MEDIATYPE_ODS,
                       version::AbstractString = DEFAULT_ODF_VERSION, check_version::Bool = true)
    write(io, package_bytes(parts; mediatype, version, check_version))
    io
end

"""
    package_bytes(parts; mediatype = MEDIATYPE_ODS, version = "1.4") -> Vector{UInt8}

The zipped package as bytes (see [`write_package`](@ref)).
"""
function package_bytes(parts; mediatype::AbstractString = MEDIATYPE_ODS,
                       version::AbstractString = DEFAULT_ODF_VERSION, check_version::Bool = true)
    check_version && _check_version(version)
    _check_parts(parts)
    mediatype in SPREADSHEET_MEDIATYPES || throw(ArgumentError("unsupported media type $(repr(mediatype))"))
    manifest = written -> manifest_xml(written, mediatype, version)
    buf = IOBuffer()
    _write_mimetype_zip(buf, mediatype)
    ZipArchives.zip_append_archive(w -> _append_parts!(w, parts, manifest), buf)
    take!(buf)
end

"""
    write_flat(dest, xml)

Write a flat ODF document (`.fods`). `xml` must be a complete `office:document` with an
`office:mimetype` attribute, or a function `xml(io)` that writes one to `io` as it makes it.
Building that document from the model belongs to the serialiser, not to the
container layer.
"""
function write_flat(path::AbstractString, xml::Union{AbstractString,Function})
    _write_replacing(tmp -> open(io -> write_flat(io, xml), tmp, "w"), path)
end

function write_flat(io::IO, xml::AbstractString)
    write(io, xml)
    io
end

function write_flat(io::IO, xml::Function)
    _write_chunked(xml, io)
    io
end
